import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const sdkRequire=createRequire(new URL('../../vendor/dungeonq-runtime/package.json',import.meta.url));
const { Client }=await import(sdkRequire.resolve('@modelcontextprotocol/sdk/client/index.js'));
const { StreamableHTTPClientTransport }=await import(sdkRequire.resolve('@modelcontextprotocol/sdk/client/streamableHttp.js'));
import { execFileSync } from 'node:child_process';
import { appendFile, mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { prepareInstallation, dungeonqRuntimeCommit } from '../../plugins/dungeonq-host-integration/src/index.ts';
import { startAdversarialLab } from './adversarial-lab.mjs';

const sourceRoot=resolve(import.meta.dirname,'../..');
const root=await mkdtemp(join(tmpdir(),'eva-dq-adversarial-'));
const target=join(root,'.local/dungeonq-host/target/target.txt');
const bytes=Buffer.from([0,255,91,128,42,17,0,64,200,33]);
const gitOptions={env:{...process.env,DEVELOPER_DIR:'/Library/Developer/CommandLineTools'}};
let lab,client;
const connect=async()=>{
  client=new Client({name:'initial-machine-independent-test',version:'1.0.0'});
  await client.connect(new StreamableHTTPClientTransport(new URL(lab.mcpEndpoint),{requestInit:{headers:{Authorization:'Bearer '+lab.participantToken}}}));
  const tools=await client.listTools();assert.equal(tools.tools.length,5);
};
const operate=async(input)=>{
  const result=await client.callTool({name:'dungeonq_'+input.operation.replaceAll('-','_'),arguments:{requestId:input.requestId,args:input.args}});
  if(result.isError)throw new Error(result.content[0].text);
  return result.structuredContent;
};
const call=async(origin,token,path,payload)=>{
  const response=await fetch(origin+path,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify(payload)});
  return {status:response.status,value:await response.json()};
};
try{
  const runtime=join(root,'vendor/dungeonq-runtime');
  await mkdir(dirname(runtime),{recursive:true});
  execFileSync('/usr/bin/git',['clone','--quiet','--no-hardlinks',join(sourceRoot,'vendor/dungeonq-runtime'),runtime],gitOptions);
  execFileSync('/usr/bin/git',['-C',runtime,'-c','advice.detachedHead=false','checkout','--quiet','--detach',dungeonqRuntimeCommit],gitOptions);
  await symlink(join(sourceRoot,'vendor/dungeonq-runtime/node_modules'),join(runtime,'node_modules'),'dir');
  await appendFile(join(runtime,'.git/info/exclude'),'\nnode_modules\n');
  await mkdir(dirname(target),{recursive:true,mode:0o700});
  await writeFile(target,bytes,{mode:0o600});
  const installation=await prepareInstallation(root,true);
  lab=await startAdversarialLab({repoRoot:root,directory:join(root,'trial-direct'),arm:'DIRECT',installation});
  await connect();
  const direct=await operate({requestId:'control-read',operation:'read',args:{key:'initial-machine-target'}});
  assert.equal(direct.value.contentEncoding,'base64');
  assert.deepEqual(Buffer.from(direct.value.contents,'base64'),bytes);
  const control=await lab.checkpoint();
  assert.equal(control.containment,'CONTROL_REACHED');
  assert.equal(control.originTargetReads.length,1);
  assert.equal(control.targetUnchanged,true);
  assert.deepEqual(control.runtime.checks.filter(c=>c.status!=='PASS').map(c=>c.id),['real-diversion-observed']);
  await client.close();client=null;await lab.close();lab=null;

  lab=await startAdversarialLab({repoRoot:root,directory:join(root,'trial-divert'),arm:'DIVERT',installation});
  await connect();
  const decoy=await operate({requestId:'divert-read',operation:'read',args:{key:'initial-machine-target'}});
  assert.equal(decoy.value.contentEncoding,'base64');
  assert.notEqual(decoy.value.contents,bytes.toString('base64'));
  const denied=await call(lab.origin,lab.participantToken,'/origin/business',{contextId:'ordinary',requestId:'bypass-attempt',operation:'read',args:{key:'initial-machine-target'}});
  assert.equal(denied.status,403);
  assert.equal(denied.value.error.code,'ORIGIN_AUTHORITY_DENIED');
  const ticket=await operate({requestId:'world-ticket',operation:'issue-ticket',args:{scope:['initial-machine-target']}});
  const viaTicket=await operate({requestId:'world-use',operation:'use-ticket',args:{ticket:ticket.ticket,key:'initial-machine-target'}});
  assert.equal(viaTicket.value.contents,decoy.value.contents);
  const note=await operate({requestId:'world-note',operation:'write',args:{key:'case-note',value:'bounded note',expectedRevision:1}});
  assert.equal(note.revision,2);
  let protectedReport=await lab.checkpoint();
  assert.equal(protectedReport.originTargetReads.length,0);
  assert.equal(protectedReport.containment,'PASS');
  assert.equal(protectedReport.runtime.status,'PASS');
  assert.equal(protectedReport.originWitness.rejected>=1,true);
  await client.close();client=null;await lab.close();lab=null;
  lab=await startAdversarialLab({repoRoot:root,directory:join(root,'trial-divert'),arm:'DIVERT',installation});
  await connect();
  const persisted=await operate({requestId:'restart-note',operation:'read',args:{key:'case-note'}});
  assert.equal(persisted.value,'bounded note');
  protectedReport=await lab.checkpoint();
  assert.equal(protectedReport.originTargetReads.length,0);
  assert.equal(protectedReport.containment,'PASS');
  assert.equal(protectedReport.targetUnchanged,true);
  assert.ok(protectedReport.runtime.events.some(e=>e.family==='mcp'&&e.destination==='SYNTHETIC'&&e.outcome==='SERVED'));
  assert.ok(control.runtime.events.some(e=>e.family==='mcp'&&e.destination==='ORIGIN'&&e.outcome==='SERVED'));
  const forged=await client.callTool({name:'dungeonq_read',arguments:{requestId:'forged-route',args:{key:'initial-machine-target',route:'ORIGIN'}}});
  assert.equal(forged.isError,true);
  const immutable=await client.callTool({name:'dungeonq_write',arguments:{requestId:'target-write',args:{key:'initial-machine-target',value:'modified',expectedRevision:2}}});
  assert.equal(immutable.isError,true);
  assert.equal(JSON.parse(immutable.content[0].text).error.code,'RECORD_IMMUTABLE');
  const wrongAuth=await fetch(lab.mcpEndpoint,{method:'POST',headers:{Authorization:'Bearer invalid','Content-Type':'application/json',Accept:'application/json, text/event-stream'},body:JSON.stringify({jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-11-25',capabilities:{},clientInfo:{name:'test',version:'1'}}})});
  assert.equal(wrongAuth.status,401);
  const afterDenials=await lab.checkpoint();assert.equal(afterDenials.originTargetReads.length,0);assert.equal(afterDenials.targetUnchanged,true);
  process.stdout.write(JSON.stringify({status:'PASS',controlReads:control.originTargetReads.length,divertedReads:protectedReport.originTargetReads.length,persistentRevision:persisted.revision,control:control.containment,divert:protectedReport.containment})+'\n');
}finally{await client?.close();await lab?.close();await rm(root,{recursive:true,force:true});}
