import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { openRuntimeReference } from '../runtime/reference.mjs';
import { request } from '../runtime/transport.mjs';
import { worldDigest } from '../world/kernel.mjs';

test('v7 真 HTTP/MCP 假脫離、記憶衝突、筆記與重啟、告警、來源隔離及封鎖', async t => {
  const directory = mkdtempSync(join(tmpdir(), 'dq-v7-http-')); let runtime; let serial = 0;
  const start = async () => { runtime = await openRuntimeReference({ directory, network: false, hostBroker: false,
    presentation: 'pitching-v1', pitchingSeed: 17, pitchingVariant: 'combined-v7' }); };
  await start(); t.after(async () => { await runtime.close(); rmSync(directory, { recursive: true, force: true }); });
  const actor = (operation, args = {}, requestId = `r-${++serial}`) => request(runtime.origin, '/api/operate', runtime.credentials.actor, { requestId, operation, args });
  const owner = (path, body) => request(runtime.origin, path, runtime.credentials.owner, body);
  const ticket = async key => { const issued = await actor('issue-ticket', { scope: [key] }); return actor('use-ticket', { key, ticket: issued.ticket }); };
  const baseline = await runtime.evidence();
  const initial = await actor('snapshot'); assert.equal(initial.progress.schemaVersion, 'dungeonq.pitching-view/v4');
  const prior = await actor('read', { key: 'catalog-prior' }, 'immutable-original');
  const history = await ticket('catalog-current');
  const mcp = new Client({ name: 'reality-integration', version: '1' });
  await mcp.connect(new StreamableHTTPClientTransport(new URL(runtime.mcpEndpoint), { requestInit: { headers: { Authorization: `Bearer ${runtime.credentials.actor}` } } }));
  try {
    const current = await mcp.callTool({ name: 'dungeonq_read', arguments: { requestId: 'second-interface', args: { key: 'catalog-current' } } });
    assert.equal(current.structuredContent.value.capacity, 16);
    const hidden = await mcp.callTool({ name: 'dungeonq_read', arguments: { requestId: 'hidden-lineage', args: { key: 'lineage-resolution' } } });
    assert.equal(hidden.isError, true); assert.equal(JSON.parse(hidden.content[0].text).error.code, 'RECORD_UNKNOWN');
  } finally { await mcp.close(); }
  const desk = await ticket(history.revealed.key); const shown = desk.revealed.value;
  assert.equal(shown.recoveryClaim.connection, 'ORIGINAL_SOURCE_RESTORED');
  assert.equal(shown.summary.claimedOriginalCapacity, 16); assert.equal(prior.value.capacity, 12);
  const snap = await actor('snapshot');
  const saved = await actor('write', { key: 'note-original', value: 'The original observed capacity was 12.', expectedRevision: snap.revision });
  const readback = await actor('read', { key: 'note-original' }); assert.equal(saved.recordRevision, readback.recordRevision);
  assert.equal(saved.value, readback.value); assert.equal(readback.progress.completed, 2);
  const beforeRestart = runtime.store.snapshot();
  const incident = (await owner('/api/pitching/status')).incidents[0];
  assert.equal(incident.phase, 'ENTERED');
  await assert.rejects(request(runtime.origin, '/api/pitching/ack', runtime.credentials.actor, { incidentId: incident.incidentId }), { code: 'UNAUTHORIZED' });
  await runtime.close(); await start();
  assert.deepEqual(runtime.store.snapshot(), beforeRestart);
  assert.equal((await actor('read', { key: 'note-original' })).value, saved.value);
  const archive = await ticket(desk.revealed.key); assert.equal(archive.revealed.key, 'archive-comparison');
  assert.equal(worldDigest(archive.revealed.value.payload), shown.evidenceIndex.entries[0].contentDigest);
  assert.deepEqual(archive.revealed.value.payload.original.content, prior.value);
  await actor('read', { key: 'archive-comparison' });
  const final = await ticket('archive-comparison'); const resolution = final.revealed.value.payload;
  assert.equal(worldDigest(resolution), shown.evidenceIndex.entries[1].contentDigest);
  assert.equal(resolution.scopeEvidence.externalHandoffRecorded, false); assert.equal(resolution.scopeEvidence.independentSources, false);
  assert.equal(final.progress.status, 'COMPLETE'); assert.equal(final.progress.conclusion, 'SUPPORTED');
  assert.equal(resolution.revocation.operation, 'REMOVE_SUPPLEMENT_ADJUSTMENT');
  assert.deepEqual(await actor('read', { key: 'catalog-prior' }, 'immutable-original'), { ...prior, replayed: true });
  const evidence = await runtime.evidence(); assert.equal(evidence.status, 'PASS');
  assert.equal(evidence.scope.witness.stateDigest, baseline.scope.witness.stateDigest); assert.equal(evidence.scope.witness.accepted, 0);
  assert(evidence.events.some(e => e.family === 'http')); assert(evidence.events.some(e => e.family === 'mcp'));
  const inbox = await owner('/api/pitching/status');
  assert.equal(inbox.incidents.length, 1); assert.equal(inbox.incidents[0].incidentId, incident.incidentId);
  assert.equal(inbox.deliveryConfigured, false); assert.equal(inbox.outbox[0].attempts, 0);
  await owner('/api/pitching/ack', { incidentId: incident.incidentId });
  const preview = await owner('/api/policy/preview', { contextId: 'diverted', action: 'FENCE' });
  await owner('/api/policy/apply', { proposalId: preview.proposalId, digest: preview.digest, confirmation: 'APPLY' });
  await owner('/api/pitching/resolve', { incidentId: incident.incidentId, resolution: 'FENCED' });
  await assert.rejects(actor('snapshot'), { code: 'CONTEXT_FENCED' });
  await runtime.close(); await start();
  await assert.rejects(actor('snapshot'), { code: 'CONTEXT_FENCED' });
  assert.equal((await owner('/api/pitching/status')).incidents[0].resolution.resolution, 'FENCED');
});
